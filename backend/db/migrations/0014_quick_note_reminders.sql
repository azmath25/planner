CREATE TABLE IF NOT EXISTS dayframe.note_alert_actions (
 owner_user_id text NOT NULL,
 note_id uuid NOT NULL,
 source_day date NOT NULL,
 source_time time NOT NULL,
 acknowledged_at timestamptz,
 snoozed_until timestamptz,
 revision integer NOT NULL DEFAULT 1 CHECK(revision>=1),
 updated_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(owner_user_id,note_id,source_day,source_time),
 FOREIGN KEY(note_id,owner_user_id) REFERENCES dayframe.quick_notes(id,owner_user_id) ON DELETE CASCADE,
 CHECK(acknowledged_at IS NULL OR snoozed_until IS NULL)
);
CREATE INDEX IF NOT EXISTS note_alert_actions_snoozed
 ON dayframe.note_alert_actions(owner_user_id,snoozed_until)
 WHERE snoozed_until IS NOT NULL;

CREATE TABLE IF NOT EXISTS dayframe.note_notification_deliveries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_user_id text NOT NULL,
 note_id uuid NOT NULL,
 source_day date NOT NULL,
 source_time time NOT NULL,
 send_after timestamptz NOT NULL,
 endpoint text NOT NULL REFERENCES dayframe.push_subscriptions(endpoint) ON DELETE CASCADE,
 status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','sending','delivered','retry','expired')),
 attempts integer NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 12),
 claimed_at timestamptz,
 next_attempt_at timestamptz NOT NULL DEFAULT now(),
 sent_at timestamptz,
 last_status smallint,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(owner_user_id,note_id,source_day,source_time,send_after,endpoint),
 FOREIGN KEY(note_id,owner_user_id) REFERENCES dayframe.quick_notes(id,owner_user_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS note_deliveries_claim
 ON dayframe.note_notification_deliveries(status,next_attempt_at,id)
 WHERE status IN ('pending','retry','sending');

CREATE OR REPLACE FUNCTION dayframe.update_note_alert(
 p_owner text,p_note uuid,p_day date,p_time time,
 p_revision integer,p_action text,p_until timestamptz
) RETURNS integer LANGUAGE plpgsql AS $note_alert$
DECLARE old_revision integer; result_revision integer;
BEGIN
 IF p_owner IS NULL OR p_note IS NULL OR p_day IS NULL OR p_time IS NULL
 OR p_action NOT IN ('acknowledge','snooze','reset') OR p_revision IS NULL OR p_revision<0
 OR (p_action='snooze' AND (p_until IS NULL OR p_until<=now() OR p_until>now()+interval '30 days'))
 OR (p_action<>'snooze' AND p_until IS NOT NULL) THEN
  RAISE EXCEPTION 'Invalid note alert action' USING ERRCODE='23514';
 END IF;
 PERFORM pg_advisory_xact_lock(hashtextextended('dayframe:note-alert:'||p_owner||':'||p_note,6020));
 IF NOT EXISTS (
  SELECT 1 FROM dayframe.quick_notes n JOIN dayframe.workspaces w
   ON w.id=n.workspace_id AND w.owner_user_id=p_owner
  WHERE n.id=p_note AND n.owner_user_id=p_owner AND n.deleted_at IS NULL
   AND w.deleted_at IS NULL AND w.archived_at IS NULL
   AND n.reminder=p_day AND COALESCE(n.reminder_time,'09:00'::time)=p_time
 ) THEN RAISE EXCEPTION 'Note reminder changed or unavailable' USING ERRCODE='40001'; END IF;
 SELECT revision INTO old_revision FROM dayframe.note_alert_actions
  WHERE owner_user_id=p_owner AND note_id=p_note
   AND source_day=p_day AND source_time=p_time FOR UPDATE;
 IF NOT FOUND THEN
  IF p_revision<>0 THEN RAISE EXCEPTION 'Note alert changed' USING ERRCODE='40001'; END IF;
  INSERT INTO dayframe.note_alert_actions
   (owner_user_id,note_id,source_day,source_time,acknowledged_at,snoozed_until)
  VALUES(p_owner,p_note,p_day,p_time,
   CASE WHEN p_action='acknowledge' THEN now() ELSE NULL END,
   CASE WHEN p_action='snooze' THEN p_until ELSE NULL END);
  RETURN 1;
 END IF;
 IF old_revision<>p_revision THEN RAISE EXCEPTION 'Note alert changed' USING ERRCODE='40001'; END IF;
 UPDATE dayframe.note_alert_actions SET
  acknowledged_at=CASE WHEN p_action='acknowledge' THEN now() ELSE NULL END,
  snoozed_until=CASE WHEN p_action='snooze' THEN p_until ELSE NULL END,
  revision=revision+1,updated_at=now()
 WHERE owner_user_id=p_owner AND note_id=p_note AND source_day=p_day AND source_time=p_time
 RETURNING revision INTO result_revision;
 RETURN result_revision;
END $note_alert$;

-- For each account's selected timezone, enqueue at most one push per
-- occurrence + fire instant + endpoint. Device payload stays empty.
CREATE OR REPLACE FUNCTION dayframe.enqueue_due_note_push(p_limit integer DEFAULT 250)
RETURNS integer LANGUAGE plpgsql AS $enqueue_notes$
DECLARE inserted_count integer;
BEGIN
 IF p_limit<1 OR p_limit>1000 THEN RAISE EXCEPTION 'Invalid batch size' USING ERRCODE='23514'; END IF;
 WITH due AS (
  SELECT n.owner_user_id,n.id AS note_id,n.reminder AS day,
   COALESCE(n.reminder_time,'09:00'::time) AS clock,
   COALESCE(a.snoozed_until,((n.reminder+COALESCE(n.reminder_time,'09:00'::time)) AT TIME ZONE p.time_zone)) AS fire_at,
   s.endpoint
  FROM dayframe.quick_notes n
  JOIN dayframe.workspaces w ON w.id=n.workspace_id AND w.owner_user_id=n.owner_user_id
  JOIN dayframe.notification_preferences p ON p.owner_user_id=n.owner_user_id
  JOIN dayframe.push_subscriptions s ON s.owner_user_id=n.owner_user_id
  LEFT JOIN dayframe.note_alert_actions a ON a.owner_user_id=n.owner_user_id
   AND a.note_id=n.id AND a.source_day=n.reminder
   AND a.source_time=COALESCE(n.reminder_time,'09:00'::time)
  WHERE n.reminder IS NOT NULL AND n.deleted_at IS NULL
   AND w.deleted_at IS NULL AND w.archived_at IS NULL AND a.acknowledged_at IS NULL
 ), eligible AS (
  SELECT * FROM due d WHERE d.fire_at<=now() AND d.fire_at>=now()-interval '7 days'
  ORDER BY d.fire_at LIMIT p_limit
 ), inserted AS (
  INSERT INTO dayframe.note_notification_deliveries
   (owner_user_id,note_id,source_day,source_time,send_after,endpoint)
  SELECT owner_user_id,note_id,day,clock,fire_at,endpoint FROM eligible
  ON CONFLICT DO NOTHING RETURNING id
 )
 SELECT count(*)::integer INTO inserted_count FROM inserted;
 RETURN inserted_count;
END $enqueue_notes$;

