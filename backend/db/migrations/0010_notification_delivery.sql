-- M4.3 delivery: account time-zone, browser push subscriptions, and durable outbox.
-- Run after 0009_reminder_actions.sql. No sample users or automatic imports.
CREATE TABLE IF NOT EXISTS dayframe.notification_preferences (
 owner_user_id text PRIMARY KEY CHECK (length(owner_user_id) BETWEEN 1 AND 256),
 time_zone text NOT NULL DEFAULT 'UTC' CHECK(length(time_zone) BETWEEN 2 AND 64),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS dayframe.push_subscriptions (
 endpoint text PRIMARY KEY CHECK(length(endpoint) BETWEEN 30 AND 1200),
 owner_user_id text NOT NULL CHECK(length(owner_user_id) BETWEEN 1 AND 256),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS push_subscriptions_owner ON dayframe.push_subscriptions(owner_user_id);
CREATE TABLE IF NOT EXISTS dayframe.notification_deliveries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_user_id text NOT NULL,
 task_id uuid NOT NULL,
 kind text NOT NULL CHECK(kind IN ('reminder','deadline')),
 source_day date NOT NULL,
 source_time time NOT NULL,
 send_after timestamptz NOT NULL,
 endpoint text NOT NULL REFERENCES dayframe.push_subscriptions(endpoint) ON DELETE CASCADE,
 status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','sending','delivered','retry','expired')),
 attempts integer NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 12),
 claimed_at timestamptz,
 next_attempt_at timestamptz NOT NULL DEFAULT now(),
 sent_at timestamptz,
 last_status smallint,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(owner_user_id,task_id,kind,source_day,source_time,send_after,endpoint),
 CONSTRAINT deliveries_task FOREIGN KEY(task_id,owner_user_id)
 REFERENCES dayframe.tasks(id,owner_user_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS deliveries_claim ON dayframe.notification_deliveries(status,next_attempt_at,id)
 WHERE status IN ('pending','retry','sending');

-- Enqueue only when an opted-in subscription exists and event is due. A
-- source-date change creates a new occurrence. Prefer the stored account zone,
-- never a browser zone that might differ by device. The outbox uniqueness
-- constraint prevents duplicate claims across scheduler invocations.
CREATE OR REPLACE FUNCTION dayframe.enqueue_due_push(p_limit integer DEFAULT 250)
RETURNS integer LANGUAGE plpgsql AS $enqueue$
DECLARE inserted_count integer;
BEGIN
 IF p_limit<1 OR p_limit>1000 THEN RAISE EXCEPTION 'Invalid batch size' USING ERRCODE='23514'; END IF;
 WITH occurrences AS (
  SELECT t.owner_user_id,t.id AS task_id,k.kind,
   CASE WHEN k.kind='reminder' THEN t.reminder ELSE t.deadline END AS day,
   COALESCE(CASE WHEN k.kind='reminder' THEN t.reminder_time ELSE t.deadline_time END,'09:00'::time) AS clock,
   p.time_zone
  FROM dayframe.tasks t
  JOIN dayframe.workspaces w ON w.id=t.workspace_id AND w.owner_user_id=t.owner_user_id
  JOIN dayframe.notification_preferences p ON p.owner_user_id=t.owner_user_id
  CROSS JOIN (VALUES('reminder'),('deadline')) AS k(kind)
  WHERE t.status='open' AND t.deleted_at IS NULL AND t.archived_at IS NULL
   AND w.deleted_at IS NULL AND w.archived_at IS NULL
 ), due AS (
  SELECT o.owner_user_id,o.task_id,o.kind,o.day,o.clock,
   COALESCE(a.snoozed_until,((o.day+o.clock) AT TIME ZONE o.time_zone)) AS fire_at,
   s.endpoint
  FROM occurrences o
  JOIN dayframe.push_subscriptions s ON s.owner_user_id=o.owner_user_id
  LEFT JOIN dayframe.task_alert_actions a ON a.owner_user_id=o.owner_user_id
   AND a.task_id=o.task_id AND a.kind=o.kind AND a.source_day=o.day AND a.source_time=o.clock
  WHERE o.day IS NOT NULL AND a.acknowledged_at IS NULL
 ), eligible AS (
  SELECT * FROM due WHERE fire_at<=now() AND fire_at>=now()-interval '7 days'
  ORDER BY fire_at LIMIT p_limit
 ), inserted AS (
  INSERT INTO dayframe.notification_deliveries
  (owner_user_id,task_id,kind,source_day,source_time,send_after,endpoint)
  SELECT owner_user_id,task_id,kind,day,clock,fire_at,endpoint FROM eligible
  ON CONFLICT DO NOTHING RETURNING id
 )
 SELECT count(*)::integer INTO inserted_count FROM inserted;
 RETURN inserted_count;
END $enqueue$;

